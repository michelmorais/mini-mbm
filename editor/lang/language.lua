-- Default from OS via mbm.getIdiom()
local function getDefaultFromOS()
    if mbm and mbm.getIdiom then
        local idiom = mbm.getIdiom() or ""
        if idiom:lower():find("pt") then
            return "pt_br"
        end
    end
    return "en"
end

-- Init: prefer stored preference, else OS
local function initLanguage()
    if mbm and mbm.getGlobal then
        local stored = mbm.getGlobal("editor_language")
        if stored == "pt_br" or stored == "en" then
            return stored
        end
    end
    return getDefaultFromOS()
end

M.current = initLanguage()

function M.setLanguage(lang)
    if lang == "pt_br" or lang == "en" then
        M.current = lang
        if mbm and mbm.setGlobal then
            mbm.setGlobal("editor_language", lang)
        end
    end
end

function M.getLanguage()
    return M.current
end

function M.L(key)
    local t = M[M.current] or M.en
    return t[key] or M.en[key] or key
end

-- Renders Language submenu. Requires tImGui in scope.
function M.renderLanguageSubmenu()
    if tImGui.BeginMenu(M.L("menu_language")) then
        local pressed_en = tImGui.MenuItem(M.L("lang_english"), nil, M.current == "en")
        if pressed_en then
            M.setLanguage("en")
        end
        local pressed_pt = tImGui.MenuItem(M.L("lang_portuguese_br"), nil, M.current == "pt_br")
        if pressed_pt then
            M.setLanguage("pt_br")
        end
        tImGui.EndMenu()
    end
end

return M
